--
--  بعد أن تحقق الغرض يُزال الافتراضي: Prisma يضبط @updatedAt في طبقة
--  التطبيق، فبقاء افتراضي في القاعدة يجعل `prisma migrate dev` يرى
--  انحرافاً (drift) في كل تشغيل ويقترح ترحيلاً لإزالته.
--
--  DROP DEFAULT على عمود بلا افتراضي عملية لاغية في PostgreSQL،
--  فالملف آمن على أي قاعدة سواء طُبّق السابق عليها أم أُنشئت من الصفر.
-- ════════════════════════════════════════════════════════════════════

